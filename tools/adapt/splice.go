// marker is the first line of every generated schema.
const marker = "      # Generated by tools/adapt from adapt/profile.yaml. Do not edit."

var schemaHeader = regexp.MustCompile(`^    ([A-Za-z0-9_.-]+):\s*$`)

// components are the schemas of openapi.yaml: their JSON type, empty for a
// schema without one, and their properties.
type components struct {
	types map[string]string
	props map[string]map[string]bool
}

func readComponents(spec []byte) (*components, error) {
	var doc struct {
		Components struct {
			Schemas map[string]struct {
				Type       any            `yaml:"type"`
				Properties map[string]any `yaml:"properties"`
			} `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(spec, &doc); err != nil {
		return nil, fmt.Errorf("openapi.yaml: %w", err)
	}
	c := &components{types: map[string]string{}, props: map[string]map[string]bool{}}
	for name, s := range doc.Components.Schemas {
		t, _ := s.Type.(string)
		c.types[name] = t
		c.props[name] = map[string]bool{}
		for p := range s.Properties {
			c.props[name][p] = true
		}
	}
	return c, nil
}

type block struct{ start, end int } // lines [start, end) of openapi.yaml

// splice replaces each generated schema's block in components/schemas,
// leaving everything else in openapi.yaml as it is.
func splice(spec []byte, schemas []genSchema) ([]byte, error) {
	lines := strings.Split(string(spec), "\n")
	blocks, err := schemaBlocks(lines)
	if err != nil {
		return nil, err
	}

	generated := map[string]bool{}
	for _, s := range schemas {
		generated[s.name] = true
		if _, ok := blocks[s.name]; !ok {
			return nil, fmt.Errorf("openapi.yaml has no schema %s; add `%s: {}` to components/schemas where it belongs", s.name, s.name)
		}
	}
	for name, bl := range blocks {
		if !generated[name] && slicesContain(lines[bl.start:bl.end], marker) {
			return nil, fmt.Errorf("openapi.yaml: schema %s was generated but is not in adapt/profile.yaml; remove it or add it to the profile", name)
		}
	}

	// Replace from the bottom up, so earlier line numbers stay valid.
	sorted := append([]genSchema(nil), schemas...)
	sort.Slice(sorted, func(i, j int) bool { return blocks[sorted[i].name].start > blocks[sorted[j].name].start })
	for _, s := range sorted {
		var b strings.Builder
		fmt.Fprintf(&b, "    %s:\n%s\n", s.name, marker)
		emitMap(&b, s.body, 6)
		text := strings.Split(strings.TrimSuffix(b.String(), "\n"), "\n")
		bl := blocks[s.name]
		lines = append(lines[:bl.start], append(text, lines[bl.end:]...)...)
	}
	return []byte(strings.Join(lines, "\n")), nil
}

// schemaBlocks finds each schema of components/schemas: from its header to
// its last non-blank line.
func schemaBlocks(lines []string) (map[string]block, error) {
	i := slicesIndex(lines, "components:")
	if i < 0 {
		return nil, fmt.Errorf("openapi.yaml has no components")
	}
	for i++; i < len(lines) && lines[i] != "  schemas:"; i++ {
		if strings.TrimSpace(lines[i]) != "" && indentOf(lines[i]) == 0 {
			return nil, fmt.Errorf("openapi.yaml has no components/schemas")
		}
	}
	blocks := map[string]block{}
	name, start, last := "", 0, 0
	closeBlock := func() {
		if name != "" {
			blocks[name] = block{start, last + 1}
		}
		name = ""
	}
	for i++; i < len(lines); i++ {
		l := lines[i]
		if strings.TrimSpace(l) == "" {
			continue
		}
		ind := indentOf(l)
		if ind > 4 {
			last = i
			continue
		}
		closeBlock()
		if ind < 4 {
			break
		}
		if m := schemaHeader.FindStringSubmatch(l); m != nil {
			name, start, last = m[1], i, i
		}
	}
	closeBlock()
	return blocks, nil
}

// verify reads the written openapi.yaml back and compares every generated
// schema with the model it was written from, so that an emitter mistake
// cannot change the specification unnoticed.
func verify(spec []byte, schemas []genSchema) error {
	var doc struct {
		Components struct {
			Schemas map[string]any `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(spec, &doc); err != nil {
		return fmt.Errorf("generated openapi.yaml does not parse: %w", err)
	}
	for _, s := range schemas {
		got := normalize(doc.Components.Schemas[s.name])
		want := normalize(s.body)
		if !reflect.DeepEqual(got, want) {
			return fmt.Errorf("generated schema %s does not read back as written:\n got  %#v\n want %#v", s.name, got, want)
		}
	}
	return nil
}

func normalize(v any) any {
	switch x := v.(type) {
	case omap:
		m := map[string]any{}
		for _, e := range x {
			m[e.k] = normalize(e.v)
		}
		return m
	case map[string]any:
		m := map[string]any{}
		for k, e := range x {
			m[k] = normalize(e)
		}
		return m
	case flowSeq:
		return normalize([]any(x))
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = normalize(e)
		}
		return out
	case folded:
		return x.text
	case int:
		return float64(x)
	}
	return v
}

func indentOf(l string) int { return len(l) - len(strings.TrimLeft(l, " ")) }

func slicesIndex(lines []string, s string) int {
	for i, l := range lines {
		if l == s {
			return i
		}
	}
	return -1
}

func slicesContain(lines []string, s string) bool { return slicesIndex(lines, s) >= 0 }
